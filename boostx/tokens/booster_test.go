// boosterPayload and boosterClaims build a Booster payload as BoostX signs it.
type boosterPayload struct {
	GID     GID     `json:"gid"`
	Round   int     `json:"round"`
	Boost   float64 `json:"boost"`
	Final   bool    `json:"final"`
	Jackpot bool    `json:"jackpot"`
}

type boosterClaims struct {
	Booster  boosterPayload `json:"booster"`
	IssuedAt int64          `json:"iat"`
}

func TestCalculateFinalCoefficient(t *testing.T) {
	testCases := []struct {
		x        float64
		boost    float64
		expected float64
	}{
		{2.0, 1.0, 2.0}, // No boost: 1 + (2-1)*1 = 2
		{2.0, 1.5, 2.5}, // 50% boost: 1 + (2-1)*1.5 = 2.5
		{3.0, 2.0, 5.0}, // 100% boost: 1 + (3-1)*2 = 5
		{1.5, 1.0, 1.5}, // No boost on 1.5x
		{1.0, 2.0, 1.0}, // Edge case: x=1 always gives 1
	}

	for _, tc := range testCases {
		result := CalculateFinalCoefficient(tc.x, tc.boost)
		if result != tc.expected {
			t.Errorf("CalculateFinalCoefficient(%v, %v) = %v, want %v", tc.x, tc.boost, result, tc.expected)
		}
	}
}

// TestFloorX covers rounds where a naive math.Floor(x*10^d)/10^d lands one
// step below the X BoostX shows, and the unset-decimals default.
func TestFloorX(t *testing.T) {
	testCases := []struct {
		xBase, boost float64
		decimals     int
		want         float64
	}{
		{1.13, 1, 2, 1.13},             // naive: 1.12
		{2.03, 1, 2, 2.03},             // naive: 2.02
		{14.95, 1.2, 2, 17.74},         // naive: 17.73
		{49.503282, 1.5, 6, 73.754923}, // naive: 73.754922
		{14.95, 1.2, 0, 17.74},         // 0 = unset decimals, floors to 2
	}

	for _, tc := range testCases {
		got := FloorX(CalculateFinalCoefficient(tc.xBase, tc.boost), tc.decimals)
		if got != tc.want {
			t.Errorf("FloorX(1 + (%v - 1) * %v, %d) = %v, want %v", tc.xBase, tc.boost, tc.decimals, got, tc.want)
		}
	}
}

// TestPlayerX covers an xBase off the decimals grid: BoostX floors it before
// boosting, so flooring only the result lands one step higher.
func TestPlayerX(t *testing.T) {
	testCases := []struct {
		xBase, boost float64
		decimals     int
		want         float64
	}{
		{1.857, 1.5, 2, 2.27}, // FloorX of the raw value alone: 2.28
		{1.857, 1, 0, 1.85},   // 0 = unset decimals, floors xBase to 2 too
		{14.95, 1.2, 2, 17.74},
	}

	for _, tc := range testCases {
		if got := PlayerX(tc.xBase, tc.boost, tc.decimals); got != tc.want {
			t.Errorf("PlayerX(%v, %v, %d) = %v, want %v", tc.xBase, tc.boost, tc.decimals, got, tc.want)
		}
	}
}

// TestFloorX_DecimalsDomain pins that decimals outside 0 and 2–6 never give a
// finite X, while the edges of the domain do.
func TestFloorX_DecimalsDomain(t *testing.T) {
	for _, decimals := range []int{0, 2, 6} {
		if x := FloorX(1.857, decimals); math.IsNaN(x) || math.IsInf(x, 0) {
			t.Errorf("FloorX(1.857, %d) = %v, want a finite X", decimals, x)
		}
		if x := PlayerX(1.857, 1.5, decimals); math.IsNaN(x) || math.IsInf(x, 0) {
			t.Errorf("PlayerX(1.857, 1.5, %d) = %v, want a finite X", decimals, x)
		}
	}
	for _, decimals := range []int{-1, 1, 7, 15} {
		if x := FloorX(1.857, decimals); !math.IsNaN(x) {
			t.Errorf("FloorX(1.857, %d) = %v, want NaN", decimals, x)
		}
		if x := PlayerX(1.857, 1.5, decimals); !math.IsNaN(x) {
			t.Errorf("PlayerX(1.857, 1.5, %d) = %v, want NaN", decimals, x)
		}
	}
}

// TestFloorX_BoostXVectors checks every vector in testdata/spec/golden/floor-x.json, golden
// vectors generated by BoostX's implementation: rawX = 1 + (xBase - 1) * boost
// without fused multiply-add, and x = the floored value the player saw.
func TestFloorX_BoostXVectors(t *testing.T) {
	data, err := os.ReadFile("../../testdata/spec/golden/floor-x.json")
	if err != nil {
		t.Fatal(err)
	}
	var vectors []struct {
		XBase    float64 `json:"xBase"`
		Boost    float64 `json:"boost"`
		Decimals int     `json:"decimals"`
		RawX     float64 `json:"rawX"`
		X        float64 `json:"x"`
	}
	if err := json.Unmarshal(data, &vectors); err != nil {
		t.Fatal(err)
	}
	if len(vectors) < 3000 {
		t.Fatalf("expected the full vector set, got %d vectors", len(vectors))
	}

	for i, v := range vectors {
		if got := CalculateFinalCoefficient(v.XBase, v.Boost); got != v.RawX {
			t.Errorf("vector %d: CalculateFinalCoefficient(%v, %v) = %v, want rawX %v", i, v.XBase, v.Boost, got, v.RawX)
		}
		if got := FloorX(v.RawX, v.Decimals); got != v.X {
			t.Errorf("vector %d: FloorX(%v, %d) = %v, want %v", i, v.RawX, v.Decimals, got, v.X)
		}
		if got := FloorX(CalculateFinalCoefficient(v.XBase, v.Boost), v.Decimals); got != v.X {
			t.Errorf("vector %d: FloorX(CalculateFinalCoefficient(%v, %v), %d) = %v, want %v", i, v.XBase, v.Boost, v.Decimals, got, v.X)
		}
	}
}

